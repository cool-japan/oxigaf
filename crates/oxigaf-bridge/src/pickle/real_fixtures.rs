/// Decodes an embedded hex fixture.
fn decode(hex: &str) -> Vec<u8> {
    assert!(
        hex.len().is_multiple_of(2),
        "fixture hex must have an even length"
    );
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("test: fixture must be valid hex"))
        .collect()
}

fn f32s(bytes: &[u8]) -> Vec<f32> {
    bytes
        .chunks_exact(4)
        .map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]]))
        .collect()
}

#[test]
fn test_reads_a_real_torch_save_archive() {
    let tensors = torch::read_checkpoint_bytes(&decode(REAL_PT_HEX))
        .expect("a real torch.save archive must read");

    let get = |name: &str| {
        tensors.iter().find(|t| t.name == name).unwrap_or_else(|| {
            panic!(
                "tensor {name} missing; got {:?}",
                tensors.iter().map(|t| &t.name).collect::<Vec<_>>()
            )
        })
    };

    // The `{"state_dict": {...}}` wrapper must be unwrapped, not treated as
    // a nesting level: the keys are `unet.conv_in.weight`, not
    // `state_dict.unet.conv_in.weight`.
    let w = get("unet.conv_in.weight");
    assert_eq!(w.dtype, Dtype::F32);
    assert_eq!(w.shape, vec![2, 2]);
    assert_eq!(f32s(&w.data), vec![1.0, 2.0, 3.0, 4.0]);

    // `torch.arange(6).reshape(2,3).t()` is a non-contiguous view sharing
    // its base's storage. Copying its storage verbatim would silently
    // transpose it; the reader must gather it into row-major order.
    let t = get("unet.t");
    assert_eq!(t.shape, vec![3, 2]);
    assert_eq!(f32s(&t.data), vec![0.0, 3.0, 1.0, 4.0, 2.0, 5.0]);

    let b = get("vae.b");
    assert_eq!(f32s(&b.data), vec![7.0]);

    // A non-float bookkeeping tensor must survive, at its original dtype.
    let ids = get("position_ids");
    assert_eq!(ids.dtype, Dtype::I64);
    assert_eq!(ids.shape, vec![3]);
}

