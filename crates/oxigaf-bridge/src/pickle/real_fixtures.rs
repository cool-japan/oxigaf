//! Regression tests against pickle streams produced by *real* Python.
//!
//! Everything else in this module is tested with hand-emitted opcodes, which
//! is precise but proves only that the reader agrees with my reading of the
//! spec. These fixtures are the bytes PyTorch 2.11, NumPy 2.4 and SciPy
//! actually wrote, so they catch the cases a spec reading misses -- and each
//! one here did:
//!
//! - NumPy 2.0 renamed `numpy.core` to `numpy._core`.
//! - Protocols 0-2 encode raw array bytes as `_codecs.encode(str, 'latin1')`.
//! - Protocol 5 pickles arrays via `numpy._core.numeric._frombuffer`, not
//!   `_reconstruct` + `BUILD`.
//! - `torch.save` writes each tensor's storage as a separate ZIP member and
//!   refers to it by persistent id, with `.t()` views sharing one storage.
//!
//! The fixtures are embedded as hex rather than checked in as binary so the
//! test suite stays hermetic (no Python needed to run it) and every byte is
//! reviewable in a diff. They were generated with:
//!
//! ```python
//! import torch, pickle, numpy as np, scipy.sparse as sp, io
//! sd = {
//!   "unet.conv_in.weight": torch.tensor([[1.0, 2.0], [3.0, 4.0]]),
//!   "unet.t": torch.arange(6, dtype=torch.float32).reshape(2, 3).t(),
//!   "vae.b": torch.tensor([7.0]),
//!   "position_ids": torch.arange(3, dtype=torch.int64),
//! }
//! buf = io.BytesIO(); torch.save({"state_dict": sd}, buf)
//! V, J = 4, 2
//! model = {
//!   "v_template": np.arange(V*3, dtype=np.float64).reshape(V, 3),
//!   "f": np.array([[0,1,2],[0,2,3]], dtype=np.int64),
//!   "shapedirs": np.arange(V*3*4, dtype=np.float64).reshape(V, 3, 4),
//!   "posedirs": np.full((V,3,9*(J-1)), 0.25, dtype=np.float64),
//!   "J_regressor": sp.csc_matrix(np.eye(J, V, dtype=np.float64)),
//!   "kintree_table": np.array([[4294967295,0],[0,1]], dtype=np.uint32),
//!   "weights": np.full((V,J), 0.5, dtype=np.float64),
//! }
//! pickle.dumps(model, protocol=2)  # and protocol=5
//! ```

