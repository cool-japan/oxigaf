#[test]
fn test_converted_flame_npy_files_load_in_oxigaf_flame() {
    // The conversion's whole purpose is that `oxigaf-flame`'s loader can
    // read what it writes, so assert against that reader's own machinery
    // (`ndarray-npy`) rather than just checking the files exist.
    use ndarray_npy::ReadNpyExt;

    let dir = tempfile::tempdir().expect("test: temp dir");
    let model_path = dir.path().join("flame.pkl");
    std::fs::write(&model_path, decode(REAL_FLAME_P2_HEX)).expect("test: write fixture");

    let out = dir.path().join("npy");
    let written = crate::convert_flame_model(&model_path, &out)
        .expect("test: FLAME conversion should succeed");
    assert_eq!(written.len(), 8, "every FLAME array must be written");

    let read_f32 = |name: &str| {
        let bytes = std::fs::read(out.join(format!("{name}.npy")))
            .unwrap_or_else(|e| panic!("test: read {name}.npy: {e}"));
        ndarray::Array2::<f32>::read_npy(std::io::Cursor::new(bytes))
            .unwrap_or_else(|e| panic!("test: ndarray-npy must read {name}.npy: {e}"))
    };

    let v_template = read_f32("v_template");
    assert_eq!(v_template.shape(), &[4, 3]);
    assert_eq!(v_template[[3, 2]], 11.0);

    let j_regressor = read_f32("j_regressor");
    assert_eq!(j_regressor.shape(), &[2, 4]);
    assert_eq!(j_regressor[[1, 1]], 1.0);

    let faces_bytes = std::fs::read(out.join("faces.npy")).expect("test: read faces.npy");
    let faces = ndarray::Array2::<i32>::read_npy(std::io::Cursor::new(faces_bytes))
        .expect("test: ndarray-npy must read faces.npy as i32");
    assert_eq!(faces.shape(), &[2, 3]);
    assert_eq!(faces[[1, 2]], 3);

    // A 3-D array must round-trip its full shape, not be flattened.
    let dirs_bytes = std::fs::read(out.join("shapedirs.npy")).expect("test: read shapedirs.npy");
    let dirs = ndarray::Array3::<f32>::read_npy(std::io::Cursor::new(dirs_bytes))
        .expect("test: ndarray-npy must read shapedirs.npy");
    assert_eq!(dirs.shape(), &[4, 3, 4]);
}

#[test]
fn test_a_real_pickle_never_executes_its_globals() {
    // The reader's central safety property, asserted against real bytes: a
    // `.pt` names `torch._utils._rebuild_tensor_v2` and
    // `collections.OrderedDict` as GLOBALs, and reading it must resolve
    // neither to a callable -- it decodes to data, and this crate decides
    // what to do with it.
    let value =
        super::vm::load(&decode(REAL_FLAME_P2_HEX)).expect("test: the FLAME pickle must decode");
    // Every constructor in the file is an inert record.
    assert!(
        value
            .get("J_regressor")
            .and_then(super::Value::class_path)
            .is_some(),
        "the sparse matrix must be recorded as a class, not constructed"
    );
}
