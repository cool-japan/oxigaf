//! Export utilities — PLY file I/O, model loading, and point-cloud rendering.
//!
//! The PLY writer produces standard 3D Gaussian Splatting ASCII PLY files that
//! are compatible with viewers like `splatfacto` and the original 3DGS codebase.
//!
//! Supported formats:
//! * PLY — Standard 3D Gaussian Splatting format
//! * safetensors — Efficient tensor storage
//! * glTF 2.0 — Standard 3D format with custom Gaussian extension
//! * JSON — Checkpoint format for resuming training

