/// Load a [`GaussianModel`] from either a checkpoint JSON file or a PLY file.
///
/// The format is determined by the file extension:
/// * `.json` — OxiGAF checkpoint (includes optimizer state, iteration, etc.)
/// * `.ply`  — Standard 3DGS PLY (position, SH, opacity, scale, rotation)
pub fn load_model(path: &Path) -> Result<GaussianModel> {
    let ext = path
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("")
        .to_lowercase();

    match ext.as_str() {
        "json" => {
            tracing::info!("Loading model from checkpoint: {}", path.display());
            let data = checkpoint::load_checkpoint(path)
                .with_context(|| format!("Failed to load checkpoint: {}", path.display()))?;
            let model = checkpoint::restore_model(&data);
            tracing::info!(
                "Restored model: {} Gaussians (iteration {})",
                model.len(),
                data.iteration,
            );
            Ok(model)
        }
        "ply" => {
            tracing::info!("Loading model from PLY: {}", path.display());
            load_ply(path)
        }
        other => {
            anyhow::bail!(
                "Unsupported model format '{}'. Expected .json (checkpoint) or .ply",
                other,
            )
        }
    }
}

