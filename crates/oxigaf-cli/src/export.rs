/// Write a [`GaussianModel`] to a safetensors file.
///
/// Tensors saved:
/// * `positions` — `[N, 3]` f32
/// * `rotations` — `[N, 4]` f32
/// * `scales`    — `[N, 3]` f32
/// * `opacities` — `[N]` f32
/// * `sh_coeffs` — `[N, C]` f32 where `C = (degree+1)² × 3`
///
/// Metadata includes `sh_degree`.
pub fn export_safetensors(model: &GaussianModel, path: &Path) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("Failed to create directory: {}", parent.display()))?;
    }

    let n = model.len();
    let sh_channels = ((model.sh_degree + 1).pow(2) * 3) as usize;

    // Extract dense f32 arrays from GaussianAttributes.
    let positions: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.position.iter().copied())
        .collect();
    let rotations: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.rotation.iter().copied())
        .collect();
    let scales: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.scale.iter().copied())
        .collect();
    let opacities: Vec<f32> = model.gaussians.iter().map(|g| g.opacity).collect();

    // Pad or truncate SH coefficients.
    let mut sh_data = model.sh_coeffs.clone();
    sh_data.resize(n * sh_channels, 0.0);

    // Build tensor views.
    let pos_view = TensorView::new(Dtype::F32, vec![n, 3], bytemuck::cast_slice(&positions))?;
    let rot_view = TensorView::new(Dtype::F32, vec![n, 4], bytemuck::cast_slice(&rotations))?;
    let scl_view = TensorView::new(Dtype::F32, vec![n, 3], bytemuck::cast_slice(&scales))?;
    let opa_view = TensorView::new(Dtype::F32, vec![n], bytemuck::cast_slice(&opacities))?;
    let sh_view = TensorView::new(
        Dtype::F32,
        vec![n, sh_channels],
        bytemuck::cast_slice(&sh_data),
    )?;

    let tensors: Vec<(&str, TensorView<'_>)> = vec![
        ("positions", pos_view),
        ("rotations", rot_view),
        ("scales", scl_view),
        ("opacities", opa_view),
        ("sh_coeffs", sh_view),
    ];

    // Metadata.
    let mut metadata = HashMap::new();
    metadata.insert("sh_degree".to_string(), model.sh_degree.to_string());
    metadata.insert("num_gaussians".to_string(), n.to_string());

    // Serialize to bytes, then write to file.
    let data = safetensors::serialize(tensors, Some(metadata))
        .map_err(|e| anyhow::anyhow!("Failed to serialize safetensors: {e}"))?;

    std::fs::write(path, &data)
        .with_context(|| format!("Failed to write safetensors file: {}", path.display()))?;

    tracing::info!(
        "Wrote {} Gaussians (SH degree {}) to {}",
        n,
        model.sh_degree,
        path.display(),
    );
    Ok(())
}

