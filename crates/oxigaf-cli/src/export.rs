/// JSON checkpoint data structure.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JsonCheckpoint {
    /// Checkpoint format version.
    pub version: String,
    /// Training iteration (0 for exported models).
    pub iteration: u32,
    /// Number of Gaussians.
    pub num_gaussians: usize,
    /// SH degree.
    pub sh_degree: u32,
    /// Gaussian positions (flattened [x, y, z, ...]).
    pub positions: Vec<f32>,
    /// Gaussian rotations (flattened [x, y, z, w, ...]).
    pub rotations: Vec<f32>,
    /// Gaussian scales (flattened [sx, sy, sz, ...]).
    pub scales: Vec<f32>,
    /// Gaussian opacities.
    pub opacities: Vec<f32>,
    /// SH coefficients (flattened).
    pub sh_coeffs: Vec<f32>,
    /// FLAME binding: face indices.
    pub face_indices: Vec<u32>,
    /// FLAME binding: barycentric coordinates.
    pub barycentric: Vec<[f32; 3]>,
    /// FLAME binding: local offsets.
    pub local_offsets: Vec<[f32; 3]>,
    /// Whether each Gaussian is rigid.
    pub is_rigid: Vec<bool>,
    /// Metadata.
    pub metadata: HashMap<String, String>,
}

/// Export a [`GaussianModel`] to JSON checkpoint format.
///
/// This format includes all Gaussian attributes and FLAME binding information,
/// making it suitable for resuming training or transferring models.
pub fn export_json_checkpoint(model: &GaussianModel, path: &Path) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("Failed to create directory: {}", parent.display()))?;
    }

    let n = model.len();

    // Extract data from model
    let positions: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.position.iter().copied())
        .collect();
    let rotations: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.rotation.iter().copied())
        .collect();
    let scales: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.scale.iter().copied())
        .collect();
    let opacities: Vec<f32> = model.gaussians.iter().map(|g| g.opacity).collect();

    let mut metadata = HashMap::new();
    metadata.insert(
        "generator".to_string(),
        format!("OxiGAF v{}", env!("CARGO_PKG_VERSION")),
    );
    metadata.insert("export_time".to_string(), chrono::Utc::now().to_rfc3339());

    let checkpoint = JsonCheckpoint {
        version: "1.0".to_string(),
        iteration: 0, // Export, not from training
        num_gaussians: n,
        sh_degree: model.sh_degree,
        positions,
        rotations,
        scales,
        opacities,
        sh_coeffs: model.sh_coeffs.clone(),
        face_indices: model.face_indices.clone(),
        barycentric: model.barycentric.clone(),
        local_offsets: model.local_offsets.clone(),
        is_rigid: model.is_rigid.clone(),
        metadata,
    };

    let json_str =
        serde_json::to_string_pretty(&checkpoint).context("Failed to serialize checkpoint")?;

    std::fs::write(path, json_str)
        .with_context(|| format!("Failed to write checkpoint: {}", path.display()))?;

    tracing::info!(
        "Wrote {} Gaussians (SH degree {}) to JSON checkpoint: {}",
        n,
        model.sh_degree,
        path.display(),
    );

    Ok(())
}

