/// Write a [`GaussianModel`] to an ASCII PLY file.
///
/// The file follows the standard 3D Gaussian Splatting format:
///
/// | Property group | Fields |
/// |----------------|--------|
/// | Position       | `x y z` |
/// | Normal         | `nx ny nz` (zeros — for compatibility) |
/// | SH DC          | `f_dc_0 f_dc_1 f_dc_2` |
/// | SH rest        | `f_rest_0 … f_rest_N` |
/// | Opacity        | `opacity` (pre-sigmoid) |
/// | Scale          | `scale_0 scale_1 scale_2` (log-scale) |
/// | Rotation       | `rot_0 rot_1 rot_2 rot_3` (w, x, y, z) |
pub fn export_ply(model: &GaussianModel, path: &Path) -> Result<()> {
    export_ply_with_metadata(model, path, None)
}

/// Write a [`GaussianModel`] to an ASCII PLY file, optionally embedding an
/// [`ExportMetadata`] block.
///
/// The metadata goes into the header as `comment oxigaf <key> <value>` lines —
/// the only channel PLY offers.  Every PLY reader (including this crate's
/// [`load_ply`]) skips unrecognised comments, so the file stays interoperable.
///
/// # Errors
///
/// Propagates directory-creation and I/O failures.
pub fn export_ply_with_metadata(
    model: &GaussianModel,
    path: &Path,
    metadata: Option<&ExportMetadata>,
) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("Failed to create directory: {}", parent.display()))?;
    }

    let file = std::fs::File::create(path)
        .with_context(|| format!("Failed to create PLY file: {}", path.display()))?;
    let mut w = BufWriter::new(file);

    let n = model.len();
    let sh_channels = ((model.sh_degree + 1).pow(2) * 3) as usize;
    let sh_rest = sh_channels.saturating_sub(3);

    // ----- Header -----
    writeln!(w, "ply")?;
    writeln!(w, "format ascii 1.0")?;
    writeln!(w, "comment Generated by OxiGAF")?;
    writeln!(w, "comment SH degree {}", model.sh_degree)?;
    if let Some(metadata) = metadata {
        // `to_key_values` guarantees single-line values, so no comment can
        // terminate the header early.
        for (key, value) in metadata.to_key_values() {
            writeln!(w, "comment oxigaf {key} {value}")?;
        }
    }
    writeln!(w, "element vertex {n}")?;
    // Position
    writeln!(w, "property float x")?;
    writeln!(w, "property float y")?;
    writeln!(w, "property float z")?;
    // Normal (compatibility — always zero)
    writeln!(w, "property float nx")?;
    writeln!(w, "property float ny")?;
    writeln!(w, "property float nz")?;
    // SH DC
    for c in 0..3 {
        writeln!(w, "property float f_dc_{c}")?;
    }
    // SH higher-order
    for i in 0..sh_rest {
        writeln!(w, "property float f_rest_{i}")?;
    }
    // Opacity, scale, rotation
    writeln!(w, "property float opacity")?;
    writeln!(w, "property float scale_0")?;
    writeln!(w, "property float scale_1")?;
    writeln!(w, "property float scale_2")?;
    writeln!(w, "property float rot_0")?;
    writeln!(w, "property float rot_1")?;
    writeln!(w, "property float rot_2")?;
    writeln!(w, "property float rot_3")?;
    writeln!(w, "end_header")?;

    // ----- Vertex data -----
    for i in 0..n {
        let g = &model.gaussians[i];
        let sh_base = i * sh_channels;

        // Position
        write!(w, "{} {} {}", g.position[0], g.position[1], g.position[2])?;
        // Normal
        write!(w, " 0 0 0")?;
        // SH DC
        for c in 0..3 {
            let v = model.sh_coeffs.get(sh_base + c).copied().unwrap_or(0.0);
            write!(w, " {v}")?;
        }
        // SH rest
        for c in 3..sh_channels {
            let v = model.sh_coeffs.get(sh_base + c).copied().unwrap_or(0.0);
            write!(w, " {v}")?;
        }
        // Opacity (pre-sigmoid)
        write!(w, " {}", g.opacity)?;
        // Scale (log-scale)
        write!(w, " {} {} {}", g.scale[0], g.scale[1], g.scale[2])?;
        // Rotation: convert from internal (x,y,z,w) → PLY (w,x,y,z)
        writeln!(
            w,
            " {} {} {} {}",
            g.rotation[3], g.rotation[0], g.rotation[1], g.rotation[2]
        )?;
    }

    w.flush()?;
    tracing::info!(
        "Wrote {} Gaussians (SH degree {}) to {}",
        n,
        model.sh_degree,
        path.display(),
    );
    Ok(())
}

