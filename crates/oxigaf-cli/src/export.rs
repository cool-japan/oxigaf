/// Export a [`GaussianModel`] to glTF 2.0 format with custom Gaussian extension.
///
/// The output is a GLB (binary glTF) file that embeds all data.
/// A custom extension `OXIGAF_gaussians` stores Gaussian-specific attributes.
///
/// If `include_metadata` is true, a metadata block describing the model is
/// included in the extension.  Use [`export_gltf_with_metadata`] to embed a
/// block that also carries training provenance read back from a checkpoint.
pub fn export_gltf(model: &GaussianModel, path: &Path, include_metadata: bool) -> Result<()> {
    let metadata = include_metadata.then(|| ExportMetadata::for_model(model));
    export_gltf_with_metadata(model, path, metadata.as_ref())
}

/// Export a [`GaussianModel`] to GLB, embedding `metadata` in the
/// `OXIGAF_gaussians` extension when it is given.
///
/// # Errors
///
/// Propagates directory-creation, serialisation, and I/O failures.
pub fn export_gltf_with_metadata(
    model: &GaussianModel,
    path: &Path,
    metadata: Option<&ExportMetadata>,
) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("Failed to create directory: {}", parent.display()))?;
    }

    let n = model.len();
    let sh_channels = ((model.sh_degree + 1).pow(2) * 3) as usize;

    // Build binary buffer with all data
    let mut buffer_data = Vec::new();
    let mut buffer_views = Vec::new();
    let mut accessors = Vec::new();

    // Helper to add a buffer view and accessor. `min_max`, when given, is
    // written to the accessor's `min`/`max` fields — the glTF 2.0 spec
    // REQUIRES these on any accessor referenced by a `POSITION` attribute
    // (used for frustum culling / auto-framing by conforming loaders).
    let mut add_accessor = |data: &[f32],
                            count: usize,
                            components: usize,
                            accessor_type: &str,
                            min_max: Option<(Vec<f32>, Vec<f32>)>|
     -> usize {
        let byte_offset = buffer_data.len();
        let byte_length = data.len() * 4;

        buffer_data.extend(bytemuck::cast_slice::<f32, u8>(data));

        let view_idx = buffer_views.len();
        buffer_views.push(GltfBufferView {
            buffer: 0,
            byte_offset,
            byte_length,
            byte_stride: if components > 1 {
                Some(components * 4)
            } else {
                None
            },
        });

        let (min, max) = match min_max {
            Some((mn, mx)) => (Some(mn), Some(mx)),
            None => (None, None),
        };
        let accessor_idx = accessors.len();
        accessors.push(GltfAccessor {
            buffer_view: view_idx,
            component_type: 5126, // FLOAT
            count,
            accessor_type: accessor_type.to_string(),
            min,
            max,
        });

        accessor_idx
    };

    // Positions (required for point cloud visualization)
    let positions: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.position.iter().copied())
        .collect();
    let pos_min_max = if n > 0 {
        let mut min = [f32::INFINITY; 3];
        let mut max = [f32::NEG_INFINITY; 3];
        for chunk in positions.chunks_exact(3) {
            for k in 0..3 {
                min[k] = min[k].min(chunk[k]);
                max[k] = max[k].max(chunk[k]);
            }
        }
        Some((min.to_vec(), max.to_vec()))
    } else {
        None
    };
    let pos_accessor = add_accessor(&positions, n, 3, "VEC3", pos_min_max);

    // Rotations (quaternion xyzw)
    let rotations: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.rotation.iter().copied())
        .collect();
    let rot_accessor = add_accessor(&rotations, n, 4, "VEC4", None);

    // Scales (log-scale)
    let scales: Vec<f32> = model
        .gaussians
        .iter()
        .flat_map(|g| g.scale.iter().copied())
        .collect();
    let scale_accessor = add_accessor(&scales, n, 3, "VEC3", None);

    // Opacities (pre-sigmoid)
    let opacities: Vec<f32> = model.gaussians.iter().map(|g| g.opacity).collect();
    let opacity_accessor = add_accessor(&opacities, n, 1, "SCALAR", None);

    // SH coefficients
    let mut sh_data = model.sh_coeffs.clone();
    sh_data.resize(n * sh_channels, 0.0);
    let sh_accessor = add_accessor(&sh_data, n * sh_channels, 1, "SCALAR", None);

    // Build glTF document
    let gaussian_ext = GaussianExtension {
        sh_degree: model.sh_degree,
        num_gaussians: n,
        rotations_accessor: rot_accessor,
        scales_accessor: scale_accessor,
        opacities_accessor: opacity_accessor,
        sh_coeffs_accessor: sh_accessor,
        metadata: metadata.cloned(),
    };

    let mut node_extensions = HashMap::new();
    node_extensions.insert(
        "OXIGAF_gaussians".to_string(),
        // Not `unwrap_or_default()`: that wrote a JSON `null` in place of the
        // whole extension, producing a file that claims `OXIGAF_gaussians` in
        // `extensionsUsed` while carrying none of the Gaussian attributes.
        serde_json::to_value(&gaussian_ext)
            .context("Failed to serialize the OXIGAF_gaussians glTF extension")?,
    );

    let document = GltfDocument {
        asset: GltfAsset {
            version: "2.0".to_string(),
            generator: format!("OxiGAF v{}", env!("CARGO_PKG_VERSION")),
        },
        scene: 0,
        scenes: vec![GltfScene {
            name: "GaussianScene".to_string(),
            nodes: vec![0],
        }],
        nodes: vec![GltfNode {
            name: "GaussianCloud".to_string(),
            mesh: Some(0),
            extensions: Some(node_extensions),
        }],
        meshes: vec![GltfMesh {
            name: "GaussianMesh".to_string(),
            primitives: vec![GltfPrimitive {
                attributes: {
                    let mut attrs = HashMap::new();
                    attrs.insert("POSITION".to_string(), pos_accessor);
                    attrs
                },
                mode: 0, // POINTS
            }],
        }],
        accessors,
        buffer_views,
        buffers: vec![GltfBuffer {
            byte_length: buffer_data.len(),
            uri: None, // Embedded in GLB
        }],
        extensions_used: vec!["OXIGAF_gaussians".to_string()],
        extensions: None,
    };

    // Write GLB file
    let json_str = serde_json::to_string(&document).context("Failed to serialize glTF document")?;

    // Pad JSON to 4-byte boundary
    let json_bytes = json_str.as_bytes();
    let json_padding = (4 - (json_bytes.len() % 4)) % 4;
    let json_chunk_length = json_bytes.len() + json_padding;

    // Pad buffer to 4-byte boundary
    let bin_padding = (4 - (buffer_data.len() % 4)) % 4;
    let bin_chunk_length = buffer_data.len() + bin_padding;

    // GLB header + chunks
    let total_length = 12 + 8 + json_chunk_length + 8 + bin_chunk_length;

    let file = std::fs::File::create(path)
        .with_context(|| format!("Failed to create glTF file: {}", path.display()))?;
    let mut w = BufWriter::new(file);

    // GLB header
    w.write_all(b"glTF")?; // Magic
    w.write_all(&2u32.to_le_bytes())?; // Version
    w.write_all(&(total_length as u32).to_le_bytes())?; // Total length

    // JSON chunk
    w.write_all(&(json_chunk_length as u32).to_le_bytes())?;
    w.write_all(&0x4E4F534Au32.to_le_bytes())?; // "JSON"
    w.write_all(json_bytes)?;
    for _ in 0..json_padding {
        w.write_all(b" ")?;
    }

    // Binary chunk
    w.write_all(&(bin_chunk_length as u32).to_le_bytes())?;
    w.write_all(&0x004E4942u32.to_le_bytes())?; // "BIN\0"
    w.write_all(&buffer_data)?;
    for _ in 0..bin_padding {
        w.write_all(&[0u8])?;
    }

    w.flush()?;

    tracing::info!(
        "Wrote {} Gaussians (SH degree {}) to glTF: {}",
        n,
        model.sh_degree,
        path.display(),
    );

    Ok(())
}

